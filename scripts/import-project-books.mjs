#!/usr/bin/env node

import { readdir, mkdir, readFile, rm, writeFile } from 'node:fs/promises'
import { createHash } from 'node:crypto'
import path from 'node:path'
import sharp from 'sharp'

const sourceRoot = process.argv[2]
if (!sourceRoot) {
  console.error('Usage: node scripts/import-project-books.mjs <work-folder>')
  process.exit(1)
}

const projectRoot = process.cwd()
const outputRoot = path.join(projectRoot, 'public/assets/projects')
const dataFile = path.join(projectRoot, 'src/data/projectBooks.generated.ts')
const imagePattern = /\.(?:jpe?g|png)$/i
const logoPattern = /^(?:logo(?:[-_.]|$)|片名(?:[-_.]|$))/i
const collator = new Intl.Collator('en', { numeric: true, sensitivity: 'base' })
const pageOrder = ['hero', 'kv', 'character', 'launch', 'countdown', 'dialogue', 'quote', 'banner']
const folderOrder = [
  'cisheng-zhiwoxin',
  'nanyang-wangshi',
  'lijiangxianziderenjianyanhuo',
  'tiangangjinhun',
  'tongquechunshen',
  'sisixiangnian',
  'sihouguimitiwotanlianai',
  'xindongweimian',
  'furenmeitiandouzaidanxindiaoma',
]

function comparePages(a, b) {
  const category = (name) => {
    const stem = name.trim().replace(/\.[^.]+$/, '').toLowerCase()
    const index = pageOrder.findIndex((prefix) => stem === prefix || stem.startsWith(`${prefix}-`))
    return index === -1 ? pageOrder.length : index
  }
  return category(a) - category(b) || collator.compare(a.trim(), b.trim())
}

async function makeVariant(source, output, width, cropToPage = false) {
  const image = sharp(source).rotate()
  if (cropToPage) {
    image.resize(width, Math.round(width * 1.5), {
      fit: 'cover',
      position: sharp.strategy.attention,
    })
  } else {
    image.resize({ width, withoutEnlargement: true })
  }
  await image
    .webp({ quality: 84, effort: 5 })
    .toFile(output)
}

await mkdir(outputRoot, { recursive: true })

// This directory contains generated derivatives only. Clearing it keeps reruns
// faithful when the user removes or replaces source images.
for (const entry of await readdir(outputRoot, { withFileTypes: true })) {
  if (entry.isFile() && /^project-\d{2}-(?:cover|page-\d{3})-(?:420|760)\.webp$/.test(entry.name)) {
    await rm(path.join(outputRoot, entry.name))
  }
}

const availableFolders = (await readdir(sourceRoot, { withFileTypes: true }))
  .filter((entry) => entry.isDirectory())
const foldersByName = new Map(availableFolders.map((entry) => [entry.name.replace(/:$/, ''), entry]))
const folders = folderOrder.map((name) => foldersByName.get(name))

if (availableFolders.length !== folderOrder.length || folders.some((folder) => !folder)) {
  const missing = folderOrder.filter((name) => !foldersByName.has(name))
  throw new Error(`Expected the configured 9 project folders. Missing: ${missing.join(', ') || 'none'}`)
}

const projects = []
const versions = {}

for (const [projectIndex, folder] of folders.entries()) {
  const folderPath = path.join(sourceRoot, folder.name)
  const files = (await readdir(folderPath, { withFileTypes: true }))
    .filter((entry) => entry.isFile() && imagePattern.test(entry.name))
    .map((entry) => entry.name)
    .sort(collator.compare)

  const logos = files.filter((name) => logoPattern.test(name))
  const pages = files.filter((name) => !logoPattern.test(name)).sort(comparePages)
  const prefix = `project-${String(projectIndex + 1).padStart(2, '0')}`
  let cover = null

  if (logos[0]) {
    cover = `${prefix}-cover`
    versions[cover] = createHash('sha256')
      .update(await readFile(path.join(folderPath, logos[0])))
      .digest('hex')
      .slice(0, 8)
    await Promise.all(
      [420, 760].map((width) =>
        makeVariant(
          path.join(folderPath, logos[0]),
          path.join(outputRoot, `${cover}-${width}.webp`),
          width,
        ),
      ),
    )
  }

  const pageAssets = []
  for (const [pageIndex, fileName] of pages.entries()) {
    const baseName = `${prefix}-page-${String(pageIndex + 1).padStart(3, '0')}`
    pageAssets.push(baseName)
    versions[baseName] = createHash('sha256')
      .update(await readFile(path.join(folderPath, fileName)))
      .digest('hex')
      .slice(0, 8)
    await Promise.all(
      [420, 760].map((width) =>
        makeVariant(
          path.join(folderPath, fileName),
          path.join(outputRoot, `${baseName}-${width}.webp`),
          width,
          true,
        ),
      ),
    )
  }

  projects.push({
    id: prefix,
    sourceName: folder.name.replace(/:$/, ''),
    cover,
    pages: pageAssets,
  })

  console.log(
    `${String(projectIndex + 1).padStart(2, '0')} ${folder.name}: ${pageAssets.length} pages${cover ? `, cover ${logos[0]}` : ', blank cover'}`,
  )
}

const generated = `/**\n * Generated by scripts/import-project-books.mjs.\n * Do not edit by hand; rerun the importer after changing /work: source images.\n */\n\nexport type ProjectBook = {\n  id: string\n  sourceName: string\n  cover: string | null\n  pages: readonly string[]\n}\n\nexport const PROJECT_BOOKS = ${JSON.stringify(projects, null, 2)} as const satisfies readonly ProjectBook[]\n\nconst PROJECT_BOOK_VERSIONS = ${JSON.stringify(versions, null, 2)} as const\n\nexport const projectBookImage = (name: string) => {\n  const version = PROJECT_BOOK_VERSIONS[name as keyof typeof PROJECT_BOOK_VERSIONS]\n  const query = version ? '?v=' + version : ''\n  return {\n    src: '/assets/projects/' + name + '-760.webp' + query,\n    srcSet:\n      '/assets/projects/' + name + '-420.webp' + query + ' 420w, ' +\n      '/assets/projects/' + name + '-760.webp' + query + ' 760w',\n  }\n}\n`

await writeFile(dataFile, generated)
console.log(`Generated ${dataFile}`)
